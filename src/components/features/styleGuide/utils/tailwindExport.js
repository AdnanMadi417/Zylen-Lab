import tailwindTheme from "theme/tailwindTheme";
import { DEFAULT_FONTS } from "../constants/tokens";
import { DEFAULT_ON_BRAND, normalizeFont } from "../hooks/useUiTemplate";

const { brandEffects, extend, screens, colors } = tailwindTheme;

const toChannels = (hex) => [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16)).join(" ");
const slug = (text) => text.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

/** Tailwind colour name for a client accent, e.g. "accent-fresh-turquoise". */
export const accentToken = (accent) => `accent-${slug(accent.label.en)}`;

/** The client's typefaces with defaults filled in: { sans, arabic, display? } as families. */
const clientFonts = (fonts = {}) => ({
  sans: normalizeFont(fonts.sans ?? DEFAULT_FONTS.sans),
  arabic: normalizeFont(fonts.arabic ?? DEFAULT_FONTS.arabic),
  display: fonts.display ? normalizeFont(fonts.display) : null,
});

// JSON with unquoted identifier keys, so it reads like a hand-written config.
const toJs = (value) => JSON.stringify(value, null, 2).replace(/"([A-Za-z_$][\w$]*)":/g, "$1:");

/** tailwind.config.js for the client's own project: shared theme + literal brand colours. */
export const buildTailwindConfig = (client) => {
  const { brand, ink, onBrand = DEFAULT_ON_BRAND, accents = [] } = client.colors;
  const fonts = clientFonts(client.fonts);
  const effects = brandEffects((n) => toChannels(brand[n]));
  const display = fonts.display ?? fonts.sans;

  const config = {
    darkMode: "class",
    content: ["./src/**/*.{js,jsx,ts,tsx}"],
    theme: {
      extend: {
        ...extend,
        fontFamily: {
          ...extend.fontFamily,
          dm: [fonts.sans.family, fonts.arabic.family, "sans-serif"],
          display: [display.family, fonts.arabic.family, "sans-serif"],
        },
        backgroundImage: { ...extend.backgroundImage, ...effects.backgroundImage },
        boxShadow: { ...extend.boxShadow, ...effects.boxShadow },
      },
      screens,
      colors: {
        ...colors,
        lightPrimary: brand[50],
        brandLinear: brand[500],
        brand,
        ink,
        "on-brand": onBrand,
        ...Object.fromEntries(accents.map((a) => [accentToken(a), a.hex])),
      },
    },
  };

  return `/** @type {import('tailwindcss').Config} */
// ${client.name.en} — generated by Zylen-Lab from ${client.slug}.
// Requires: npm i -D tailwindcss@3 tailwindcss-rtl
module.exports = ${toJs(config).replace(/\n}$/, ',\n  plugins: [require("tailwindcss-rtl")],\n}')};
`;
};

/** src/index.css for the client's project: Google Fonts + base typography. */
export const buildIndexCss = (client) => {
  const fonts = clientFonts(client.fonts);
  const families = [fonts.sans, fonts.arabic, fonts.display].filter(Boolean);
  const query = families
    .map(({ family, weights }) => `family=${encodeURIComponent(family).replace(/%20/g, "+")}:wght@${weights}`)
    .join("&");
  const display = fonts.display ?? fonts.sans;

  return `/* ${client.name.en} — generated by Zylen-Lab from ${client.slug}. */
@import url('https://fonts.googleapis.com/css2?${query}&display=swap');

@tailwind base;
@tailwind components;
@tailwind utilities;

@layer base {
  html {
    font-family: '${fonts.sans.family}', sans-serif;
  }

  html[dir="rtl"] {
    font-family: '${fonts.arabic.family}', sans-serif;
  }

  h1, h2, h3 {
    font-family: '${display.family}', '${fonts.arabic.family}', sans-serif;
  }
}
`;
};
